#!/usr/bin/env node
// Bakes a static campus coordinate table into src/data/buildings.json.
//
// Why static: "I'm at PMU, where should I eat" needs a coordinate for PMU, and
// neither Purdue.io nor the HFS dining API exposes one. Geocoding at request
// time would add a network hop and a rate limit to every question. Buildings
// do not move, so this is fetched once at build time and shipped as data.
//
// Run: node scripts/build-buildings.mjs
import { writeFileSync, mkdirSync } from "node:fs";

const UA = { "user-agent": "purdue-mcp (build step; github.com/sharziki/purdue-mcp)" };
const get = async (url, body) =>
  (await fetch(url, body ? { method: "POST", body, headers: UA } : { headers: UA })).json();

// Buildings OSM names differently, or does not carry at all.
const MANUAL = {
  PMU:  { lat: 40.42490, lon: -86.91095 }, // Purdue Memorial Union
  KRAN: { lat: 40.42368, lon: -86.91094 },
  RAWL: { lat: 40.42369, lon: -86.90978 },
};
// Purdue.io and OSM disagree on some codes; both spellings should resolve.
const ALIASES = { BHEE: "BRNG", HICKS: "HIKS" };

const buildings = (await get("https://api.purdue.io/odata/Buildings")).value
  .filter((b) => b.ShortCode && b.Name);
const official = new Map(buildings.map((b) => [b.ShortCode.trim().toUpperCase(), b.Name.trim()]));

const query =
  '[out:json][timeout:90];(way["name"](40.410,-86.945,40.445,-86.895);' +
  'relation["name"](40.410,-86.945,40.445,-86.895);' +
  'node["name"](40.410,-86.945,40.445,-86.895););out center tags;';
const osm = (await get("https://overpass-api.de/api/interpreter",
  new URLSearchParams({ data: query }))).elements;

const norm = (s) => String(s || "").toLowerCase()
  .replace(/\(.*?\)/g, " ")
  .replace(/\b(hall|building|bldg|center|centre|the|of|and|residence|laboratory|lab)\b/g, " ")
  .replace(/[^a-z0-9]+/g, " ").trim();

const out = {};
const byName = new Map();
for (const e of osm) {
  const c = e.center || e;
  const name = e.tags?.name;
  if (!name || typeof c.lat !== "number") continue;
  // OSM encodes the official short code in the name: "Lawson Hall (LWSN)".
  const code = (name.match(/\(([A-Z]{2,6}\d?)\)\s*$/)?.[1] || e.tags.ref || "").toUpperCase();
  if (code && official.has(code) && !out[code]) {
    out[code] = { name: official.get(code), lat: +c.lat.toFixed(6), lon: +c.lon.toFixed(6) };
  }
  if (!byName.has(norm(name))) byName.set(norm(name), [+c.lat.toFixed(6), +c.lon.toFixed(6)]);
}
for (const [code, name] of official) {
  if (out[code]) continue;
  const hit = byName.get(norm(name));
  if (hit) out[code] = { name, lat: hit[0], lon: hit[1] };
}
for (const [code, pt] of Object.entries(MANUAL)) {
  out[code] = { name: official.get(code) || code, lat: pt.lat, lon: pt.lon };
}
for (const [from, to] of Object.entries(ALIASES)) {
  if (out[to] && !out[from]) out[from] = { ...out[to], name: official.get(from) || out[to].name };
  if (out[from] && !out[to]) out[to] = { ...out[from] };
}

mkdirSync("src/data", { recursive: true });
// Emitted as TypeScript, not JSON: tsconfig is module Node16, where a JSON
// import needs an import attribute that Node16 will not accept, and a .json
// under src would also have to be copied into dist by hand.
const header =
  "// GENERATED by scripts/build-buildings.mjs -- do not edit by hand.\n" +
  "// Campus building coordinates, baked at build time so answering\n" +
  "// \"what's near PMU\" costs no network hop. Buildings do not move.\n" +
  "export type Building = { name: string; lat: number; lon: number };\n" +
  "export const BUILDINGS: Record<string, Building> = ";
writeFileSync("src/data/buildings.ts", `${header}${JSON.stringify(out, null, 2)};\n`);
const want = ["PMU", "BHEE", "BRNG", "LWSN", "WALC", "CL50", "MSEE", "KRAN", "RAWL", "HIKS", "EE", "HAMP"];
console.log(`buildings with coordinates: ${Object.keys(out).length} of ${official.size}`);
console.log("spot check:", want.map((c) => `${c}${out[c] ? "" : " MISSING"}`).join("  "));
